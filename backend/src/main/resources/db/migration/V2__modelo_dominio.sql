CREATE FUNCTION mycar.normalizar_texto(p_texto TEXT) RETURNS TEXT
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
SET search_path = pg_catalog AS $$
 SELECT regexp_replace(translate(lower(btrim(p_texto)),
 'áéíóúüñàèìòùâêîôûäëïöç','aeiouunaeiouaeiouaeioc'), '\s+', ' ', 'g')
$$;

